_TASK_RULES = """Правила извлечения задач:
- Извлекай только конкретные, действительно поручаемые задачи — не общие обсуждения, не риторические вопросы, не смолл-ток.
- Личная просьба что-то не забыть/напомнить/записать (например "напомни мне встречу на 15:00 в среду") — это тоже задача, даже если это одно сообщение без диалога и без явного второго участника: раз указаны конкретные время/дата/действие, не отбрасывай её как неоднозначную только из-за того, что это единственное сообщение.
- Если задача уже явно закрыта в переписке ("сделано", "готово") — не включай её.
- Если из сообщения не ясно, что именно нужно сделать — пропусти, лучше пропустить, чем выдумать.
- Заголовок задачи — короткий, по сути (до ~80 символов). Если в переписке явно назван ответственный (по имени) — начни заголовок с этого имени и двоеточия, например "Дима: Встреча с банком в 14:00", а дальше уже сама суть задачи; если ответственный не назван — просто суть задачи, без имени в начале. Описание — 1-3 предложения с контекстом и прямой цитатой источника; если назвал ответственного, продублируй это в описании как "Похоже, ответственный: <имя>" (это только предположение, не факт).
- Если явно назван ответственный — дополнительно укажи его в отдельном поле "assignee_name": только имя, как оно прозвучало в переписке, без лишних слов (например "Дима", "Николай", "Ник"); если ответственный не назван — assignee_name — пустая строка "".
- Заголовок и описание задачи пиши на том же языке, на котором идёт сама переписка (даже если эти правила изложены по-русски) — если чат на английском, заголовок и описание тоже должны быть на английском; если на русском — на русском; если смешанный — выбирай язык, на котором задана сама поручаемая часть.
- Приоритет — "urgent"/"high"/"normal"/"low", по умолчанию "normal", "urgent"/"high" только если в переписке явно есть срочность/дедлайн/эскалация."""


# Для чата, уже закреплённого за одним проектом — классификация не нужна, весь чат и так один проект.
