def _extract_json_object(text: str) -> str | None:
    """Вырезает первый сбалансированный {...} блок из текста — на случай если модель,
    вопреки системному промпту, добавила пояснение до/после JSON (см. QA-ревью 07.09:
    экстрактор изредка не даёт чистый JSON, из-за чего задача могла тихо теряться)."""
    start = text.find("{")
    if start == -1:
        return None
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        if depth == 0:
            return text[start : i + 1]
    return None


def _call_extractor(system_prompt: str, chat_title: str, messages: list[dict]) -> list[dict]:
    """messages — список {"user_name": str, "text": str, "ts": float} в хронологическом порядке."""
    if not messages:
        return []

    transcript_lines = [f"{m['user_name']}: {m['text']}" for m in messages]
    transcript = "\n".join(transcript_lines)

    user_content = f"Групповой чат: «{chat_title}»\n\nПереписка:\n{transcript}"

    response = client.messages.create(
        model=config.LIGHT_MODEL_NAME,
        max_tokens=2048,
        system=system_prompt,
        messages=[{"role": "user", "content": user_content}],
    )

    raw = "\n".join(block.text for block in response.content if block.type == "text").strip()
    # На случай если модель всё же обернула ответ в ```json ... ```
    if raw.startswith("```"):
        raw = raw.strip("`")
        if raw.lower().startswith("json"):
            raw = raw[4:]
        raw = raw.strip()

    parsed = None
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError:
        # Первая попытка не удалась — пробуем вырезать сбалансированный {...} блок
        # из ответа (модель могла добавить пояснение до/после JSON) и распарсить его
        # отдельно, прежде чем сдаваться и терять все задачи из сообщения.
        candidate = _extract_json_object(raw)
        if candidate is not None:
            try:
                parsed = json.loads(candidate)
            except json.JSONDecodeError:
                parsed = None
    if parsed is None:
        logger.warning("Не удалось распарсить JSON от экстрактора задач, сырой ответ: %s", raw[:500])
        return []
    tasks = parsed.get("tasks", [])
    if not isinstance(tasks, list):
        logger.warning("Поле tasks в ответе экстрактора не список, сырой ответ: %s", raw[:500])
        return []
    return tasks


def extract_tasks(chat_title: str, messages: list[dict]) -> list[dict]:
    """Для чата, уже закреплённого за одним проектом — без классификации, весь чат про один проект."""
    return _call_extractor(_SYSTEM_PROMPT, chat_title, messages)


def extract_tasks_classified(chat_title: str, messages: list[dict]) -> list[dict]:
    """Для чата без закреплённого проекта ("группа про всё подряд") — каждая задача дополнительно
    помечена полем "project" (atlas/altyn/bestswift/unsorted)."""
    return _call_extractor(_CLASSIFY_SYSTEM_PROMPT, chat_title, messages)
